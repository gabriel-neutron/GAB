// The door signs, and it names no person. Nothing authenticates a caller here, so a name would
// be a fiction that the decided act carries for ever. The writer states no more than itself.

/** Who the record records as the author of a decision. Both doors take the same word. */
export const DECIDED_BY = 'the writer door';

// The text of the door, and not a copy of it. Two paths promote a proposal — the operator signs
// a new act, and the operator decides one that waits — and a second copy of the call drifts from
// the first on the day the door takes another argument.
export const PROMOTE_PROPOSAL = 'SELECT public.promote_proposal($1::uuid, $2::text) AS id';
