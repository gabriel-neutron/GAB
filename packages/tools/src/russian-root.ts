/** The roots and the hosts for which a read accepts one more root. */
export interface ExtraRoot {
  readonly hosts: readonly string[];
  readonly pem: string;
}

export const RUSSIAN_ROOT: ExtraRoot = { hosts: RUSSIAN_ROOT_HOSTS, pem: RUSSIAN_ROOT_PEM };

/** True when `host` is on the list or is a subdomain of a host on the list. */
export const listedHost = (host: string, extra: ExtraRoot): boolean => {
  const name = host.toLowerCase().replace(/\.$/u, '');
  return extra.hosts.some((listed) => name === listed || name.endsWith(`.${listed}`));
};

/** The roots of one request: those of Node, and the extra root when the host is on the list. The
 * answer is undefined when the host is not on the list, so the request keeps its default roots. */
export const rootsFor = (host: string, extra: ExtraRoot): string[] | undefined =>
  listedHost(host, extra) ? [...rootCertificates, extra.pem] : undefined;
